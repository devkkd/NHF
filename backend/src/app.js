import express from 'express';
import cors from 'cors';
import cookieParser from 'cookie-parser';
import authRoutes from './routes/authRoutes.js';
import categoryRoutes from './routes/categoryRoutes.js';
import productRoutes from './routes/productRoutes.js';
import uploadRoutes from './routes/uploadRoutes.js';
const app = express();
app.use(cors({ origin: process.env.CLIENT_URL || 'http://localhost:3000', credentials:true, methods:['GET','POST','PUT','PATCH','DELETE','OPTIONS'], allowedHeaders:['Content-Type','Authorization'] }));
app.options('*', cors());
app.use(express.json());
app.use(express.urlencoded({ extended:true }));
app.use(cookieParser());
app.get('/health', (req,res) => res.json({ status:'OK', timestamp: new Date() }));
app.use('/api/v1/auth', authRoutes);
app.use('/api/v1/categories', categoryRoutes);
app.use('/api/v1/products', productRoutes);
app.use('/api/v1/upload', uploadRoutes);
app.use((err, req, res, next) => { console.error(err); res.status(err.status||500).json({ ok:false, error:err.message||'Internal Server Error' }); });
export default app;
